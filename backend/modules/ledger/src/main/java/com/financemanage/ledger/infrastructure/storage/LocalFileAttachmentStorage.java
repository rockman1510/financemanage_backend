package com.financemanage.ledger.infrastructure.storage;

import com.financemanage.ledger.application.AttachmentStorage;
import com.financemanage.shared.domain.NotFoundException;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/** Stores attachments as files under {@code app.ledger.attachments.directory}, one folder per user. */
@Component
class LocalFileAttachmentStorage implements AttachmentStorage {

    private final Path root;

    LocalFileAttachmentStorage(@Value("${app.ledger.attachments.directory:./data/attachments}") String directory) {
        this.root = Path.of(directory).toAbsolutePath().normalize();
    }

    @Override
    public void store(String key, InputStream content) {
        Path target = resolve(key);
        try {
            Files.createDirectories(target.getParent());
            Files.copy(content, target, StandardCopyOption.REPLACE_EXISTING);
        } catch (IOException e) {
            throw new UncheckedIOException("Could not store attachment " + key, e);
        }
    }

    @Override
    public InputStream open(String key) {
        try {
            return Files.newInputStream(resolve(key));
        } catch (NoSuchFileException e) {
            throw new NotFoundException("Attachment file", key);
        } catch (IOException e) {
            throw new UncheckedIOException("Could not read attachment " + key, e);
        }
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            throw new UncheckedIOException("Could not delete attachment " + key, e);
        }
    }

    /** Keys are generated by the application; this still refuses any key that would escape the root folder. */
    private Path resolve(String key) {
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root) || path.equals(root)) {
            throw new IllegalArgumentException("Invalid attachment key " + key);
        }
        return path;
    }
}
